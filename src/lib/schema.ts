// The five PMS tables (plus the demo email outbox), in Postgres SQL.
// Run automatically on first connect; "IF NOT EXISTS" makes it safe to run again.

export const SCHEMA = `
CREATE TABLE IF NOT EXISTS employees (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clerk_user_id   TEXT UNIQUE,                       -- filled in on first Clerk sign-in
  full_name       TEXT NOT NULL,
  email           TEXT NOT NULL UNIQUE,
  designation     TEXT NOT NULL,
  department      TEXT NOT NULL,
  date_of_joining DATE NOT NULL,
  manager_id      INTEGER REFERENCES employees(id),  -- points back to the same table
  role            TEXT NOT NULL DEFAULT 'employee' CHECK (role IN ('employee','hr_admin')),
  is_active       INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS review_cycles (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL,
  start_date DATE NOT NULL,
  end_date   DATE NOT NULL,
  status     TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','open','closed')),
  created_by INTEGER REFERENCES employees(id)
);

CREATE TABLE IF NOT EXISTS goals (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id     INTEGER NOT NULL REFERENCES employees(id),
  cycle_id        INTEGER NOT NULL REFERENCES review_cycles(id),
  title           TEXT NOT NULL,
  description     TEXT NOT NULL DEFAULT '',
  weightage       INTEGER NOT NULL CHECK (weightage BETWEEN 1 AND 100),
  target_date     DATE NOT NULL,
  status          TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','submitted','approved','sent_back')),
  manager_comment TEXT
);

CREATE TABLE IF NOT EXISTS reviews (
  id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id            INTEGER NOT NULL REFERENCES employees(id),
  manager_id             INTEGER REFERENCES employees(id),
  cycle_id               INTEGER NOT NULL REFERENCES review_cycles(id),
  status                 TEXT NOT NULL DEFAULT 'not_started'
                         CHECK (status IN ('not_started','self_submitted','manager_reviewed','completed')),
  overall_self_rating    INTEGER CHECK (overall_self_rating BETWEEN 1 AND 5),
  overall_manager_rating INTEGER CHECK (overall_manager_rating BETWEEN 1 AND 5),
  manager_summary        TEXT,
  submitted_at           TEXT,
  reviewed_at            TEXT,
  UNIQUE (employee_id, cycle_id)  -- one review per employee per cycle
);

CREATE TABLE IF NOT EXISTS goal_ratings (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  review_id       INTEGER NOT NULL REFERENCES reviews(id),
  goal_id         INTEGER NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
  self_comment    TEXT,
  self_rating     INTEGER CHECK (self_rating BETWEEN 1 AND 5),
  manager_comment TEXT,
  manager_rating  INTEGER CHECK (manager_rating BETWEEN 1 AND 5),
  UNIQUE (review_id, goal_id)
);

CREATE TABLE IF NOT EXISTS emails (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  to_email   TEXT NOT NULL,
  subject    TEXT NOT NULL,
  body       TEXT NOT NULL,
  sent_via   TEXT NOT NULL,
  created_at TEXT NOT NULL
);

-- Only one cycle may be open at a time (enforced by the database too, not just the app).
CREATE UNIQUE INDEX IF NOT EXISTS one_open_cycle ON review_cycles (status) WHERE status = 'open';

-- Row Level Security ON with no policies: Supabase's public API (anon key) can read nothing.
-- Only our server, connecting with the database password, can read and write. Every page checks roles first.
ALTER TABLE employees     ENABLE ROW LEVEL SECURITY;
ALTER TABLE review_cycles ENABLE ROW LEVEL SECURITY;
ALTER TABLE goals         ENABLE ROW LEVEL SECURITY;
ALTER TABLE reviews       ENABLE ROW LEVEL SECURITY;
ALTER TABLE goal_ratings  ENABLE ROW LEVEL SECURITY;
ALTER TABLE emails        ENABLE ROW LEVEL SECURITY;
`;

